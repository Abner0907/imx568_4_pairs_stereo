#!/usr/bin/env python3
"""Generate tegra194-camera-imx568-fpc-8cam.dtsi  (variant A, default).

AGX Xavier devkit camera connector -> AGX adapter board -> 4 x FPC -> 4 stereo
boards. Each stereo board's CrossLink-NX merges left (VC0) + right (VC1) into
one x4 CSI-2 port; board k uses bricks (2k, 2k+1).

I2C (i2c@3180000 = I2C_GP3 on the connector):
  0x20  TCA6416A  P0[3:0] PWR_EN k, P0[7:4] VIN_EN k, P1[3:0] STATUS k
  0x70  TCA9546A  channel k -> FPC k:  IMX568 left 0x36 (SLAMODE=0), right 0x3D (SLAMODE=7)
"""
import os

from gen_dtsi import CSI, PAIR_NAMES, mode_nodes, vi_and_csi

HDR = r"""/*
 * tegra194-camera-imx568-fpc-8cam.dtsi  -- GENERATED by gen_dtsi_fpc.py
 *
 * 8 x IMX568 = 4 stereo boards on FPC, Jetson AGX Xavier (L4T R35.x).
 * Include from your board .dts (e.g. tegra194-p2888-0001-p2822-0000.dts):
 *     #include "tegra194-camera-imx568-fpc-8cam.dtsi"
 * and disable other camera overlays that use i2c@3180000 / nvcsi.
 */
#include <dt-bindings/gpio/gpio.h>
#include <dt-bindings/gpio/tegra194-gpio.h>

/* Xavier GPIO on connector pin 92 (CAM1_RST) -> TCA6416A RESET#.
 * VERIFY the Tegra GPIO behind CAM1_RST in the devkit carrier spec / pinmux. */
#ifndef ADAPTER_EXP_RESET_GPIO
#define ADAPTER_EXP_RESET_GPIO TEGRA194_MAIN_GPIO(H, 6)
#endif
"""


def regulators():
    out = []
    for k in range(4):
        out.append(f"""
	vin_stereo{k}: regulator-vin-stereo{k} {{	/* 5 V to FPC {k}: FPGA + board supplies */
		compatible = "regulator-fixed";
		regulator-name = "vin-stereo{k}";
		regulator-min-microvolt = <5000000>;
		regulator-max-microvolt = <5000000>;
		gpio = <&cam_exp {4 + k} GPIO_ACTIVE_HIGH>;	/* TCA6416A P0{4 + k} */
		enable-active-high;
		regulator-boot-on;
		regulator-always-on;			/* FPGA stays configured */
		startup-delay-us = <50000>;		/* FPGA config from SPI flash */
	}};

	vdd_stereo{k}: regulator-vdd-stereo{k} {{	/* PWR_EN: FPGA sequences both sensors */
		compatible = "regulator-fixed";
		regulator-name = "vdd-stereo{k}";
		regulator-min-microvolt = <1800000>;
		regulator-max-microvolt = <1800000>;
		gpio = <&cam_exp {k} GPIO_ACTIVE_HIGH>;	/* TCA6416A P0{k} */
		enable-active-high;
		vin-supply = <&vin_stereo{k}>;
		startup-delay-us = <25000>;		/* 3 x 2 ms rails + 5 ms + XCLR/INCK + margin */
		off-on-delay-us = <20000>;		/* ordered power-down (stereo_ctrl.v) */
	}};""")
    return "".join(out)


def sensor(k, side, vc):
    nv_port, _, sif = CSI[k]
    addr = 0x36 if side == "l" else 0x3D
    idx = 2 * k + vc
    return f"""
			imx568_{idx}: imx568_{side}@{addr:x} {{	/* stereo {k} {'left' if vc == 0 else 'right'} */
				compatible = "sony,imx568";
				reg = <0x{addr:x}>;		/* SLAMODE = {0 if vc == 0 else 7} (DS 14.4); never use 0x1a here */
				devnode = "video{idx}";
				physical_w = "6.708";
				physical_h = "5.612";
				sensor_model = "imx568";
				use_sensor_mode_id = "true";
				post_crop_frame_drop = "0";
				vdd-stereo-supply = <&vdd_stereo{k}>;	/* shared with the other sensor */
				status-gpios = <&cam_exp {8 + k} GPIO_ACTIVE_HIGH>;	/* TCA6416A P1{k} */
				imx568,ready-timeout-ms = <200>;
				imx568,sync-mode = "fast-trigger";	/* or "master" for bring-up */
{mode_nodes(sif, vc, serdes=False)}

				ports {{
					#address-cells = <1>;
					#size-cells = <0>;
					port@0 {{
						reg = <0>;
						imx568_out{idx}: endpoint {{
							vc-id = <{vc}>;		/* set by the FPGA aggregator */
							port-index = <{nv_port}>;
							bus-width = <4>;
							remote-endpoint = <&imx568_csi_in{idx}>;
						}};
					}};
				}};
			}};"""


def mux_channel(k):
    return f"""
		i2c@{k} {{	/* FPC {k}: stereo {k} ({PAIR_NAMES[k]}) */
			reg = <{k}>;
			i2c-mux,deselect-on-exit;
			#address-cells = <1>;
			#size-cells = <0>;
{sensor(k, "l", 0)}
{sensor(k, "r", 1)}
		}};"""


def platform():
    pos = ['front', 'rear', 'topleft', 'topright', 'bottomleft', 'bottomright', 'centerleft', 'centerright']
    mods = []
    for k in range(4):
        for vc, side in ((0, "l"), (1, "r")):
            i = 2 * k + vc
            addr = 0x36 if side == "l" else 0x3D
            mods.append(f"""
			module{i} {{
				badge = "imx568_{PAIR_NAMES[k]}_{'left' if vc == 0 else 'right'}";
				position = "{pos[i]}";
				orientation = "1";
				drivernode0 {{
					pcl_id = "v4l2_sensor";
					devname = "imx568 {30 + k}-00{addr:02x}";
					proc-device-tree = "/proc/device-tree/i2c@3180000/tca9546@70/i2c@{k}/imx568_{side}@{addr:x}";
				}};
			}};""")
    return "".join(mods)


def main():
    vi, cs = vi_and_csi()
    body = f"""{HDR}
/ {{{regulators()}

	tegra-capture-vi {{
		num-channels = <8>;
		ports {{
			#address-cells = <1>;
			#size-cells = <0>;{vi}
		}};
	}};

	host1x@13e00000 {{
		nvcsi@15a00000 {{
			num-channels = <8>;
			#address-cells = <1>;
			#size-cells = <0>;{cs}
		}};
	}};

	i2c@3180000 {{			/* I2C_GP3 on the camera connector (pins 75/77) */
		cam_exp: gpio@20 {{
			compatible = "ti,tca6416";
			reg = <0x20>;
			gpio-controller;
			#gpio-cells = <2>;
			reset-gpios = <&tegra_main_gpio ADAPTER_EXP_RESET_GPIO GPIO_ACTIVE_LOW>;
		}};

		tca9546@70 {{
			compatible = "nxp,pca9546";
			reg = <0x70>;
			#address-cells = <1>;
			#size-cells = <0>;
			skip_mux_detect = "yes";
			force_bus_start = <30>;	/* mux channels become i2c-30..33 */
{''.join(mux_channel(k) for k in range(4))}
		}};
	}};

	tegra-camera-platform {{
		compatible = "nvidia, tegra-camera-platform";
		num_csi_lanes = <16>;
		max_lane_speed = <1500000>;
		min_bits_per_pixel = <12>;
		vi_peak_byte_per_pixel = <2>;
		vi_bw_margin_pct = <25>;
		max_pixel_rate = <2400000>;
		isp_peak_byte_per_pixel = <5>;
		isp_bw_margin_pct = <25>;
		modules {{{platform()}
		}};
	}};
}};
"""
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tegra194-camera-imx568-fpc-8cam.dtsi")
    with open(out, "w") as fh:
        fh.write(body)
    print(out)


if __name__ == "__main__":
    main()
