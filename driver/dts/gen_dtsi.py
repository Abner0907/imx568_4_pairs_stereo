#!/usr/bin/env python3
"""Generate tegra194-camera-imx568-gmsl-8cam.dtsi (Jetson AGX Xavier, L4T R35).

4 x MAX9296A on the camera I2C bus (i2c@3180000) behind a TCA9546A mux,
2 x (MAX9295A + IMX568) per deserializer -> 4 x4 CSI ports, VC0/VC1 each.
Stereo pair k = deserializer k: link A = left camera, link B = right camera.
"""
import os

# deserializer k -> Tegra CSI brick. nvcsi port-index uses the brick number;
# NVIDIA (forum t/212181) states the vi-scope port-index for the G/H brick is 5.
CSI = [  # (nvcsi port-index, vi port-index, tegra_sinterface)
    (0, 0, "serial_a"),
    (2, 2, "serial_c"),
    (4, 4, "serial_e"),
    (6, 5, "serial_g"),
]
PAIR_NAMES = ["front", "rear", "left", "right"]

MODES = [  # must match imx568_frmfmt[] order in imx568_mode_tbls.h
    dict(w=1224, h=1024, line_length=600, maxfps=60, defexp=5000, maxexp=15000),
    dict(w=2448, h=2048, line_length=1100, maxfps=30, defexp=5000, maxexp=30000),
]

HDR = r"""/*
 * tegra194-camera-imx568-gmsl-8cam.dtsi  -- GENERATED by gen_dtsi.py
 *
 * 8 x IMX568 (4 stereo pairs) over GMSL2 on Jetson AGX Xavier (L4T R35.x).
 * Include from your board .dts (e.g. tegra194-p2888-0001-p2822-0000.dts):
 *     #include "tegra194-camera-imx568-gmsl-8cam.dtsi"
 *
 * EDIT THE BOARD MACROS BELOW to match your carrier/camera schematics.
 */
#include <dt-bindings/gpio/tegra194-gpio.h>

/* ---- carrier board: MAX9296A reset (PWDNB) GPIOs from the Xavier camera connector */
#ifndef DES0_PWDN_GPIO
#define DES0_PWDN_GPIO TEGRA194_MAIN_GPIO(H, 3)	/* CAM0_PWDN  - VERIFY */
#define DES1_PWDN_GPIO TEGRA194_MAIN_GPIO(H, 6)	/* CAM1_PWDN  - VERIFY */
#define DES2_PWDN_GPIO TEGRA194_MAIN_GPIO(T, 6)	/* CAM2_PWDN  - VERIFY */
#define DES3_PWDN_GPIO TEGRA194_MAIN_GPIO(T, 7)	/* CAM3_PWDN  - VERIFY */
#endif

/* ---- camera head: MAX9295A MFP numbers (0..10) used for each function.
 * Must match the camera-head schematic; avoid MFPs strapped/used for
 * CFG, LOCK, ERRB, RCLKOUT or I2C pass-through (see MAX9295A DS). */
#define SER_MFP_EN_1V1	0
#define SER_MFP_EN_1V8	1
#define SER_MFP_EN_2V9	2
#define SER_MFP_EN_3V3	3
#define SER_MFP_XCLR	4
#define SER_MFP_XTRIG	7
#define SER_MFP_TOUT0	8

/* ---- MAX9296A: MFP that receives TRIGk from the sync controller and
 * forwards it as GMSL GPIO ID 0 to both links.  GPIO block base and bit
 * layout (GPIO_A: [1]=GPIO_TX_EN [0]=GPIO_OUT_DIS, GPIO_B[4:0]=TX_ID)
 * - VERIFY against the MAX9296A user guide before first power-up. */
#define DES_TRIG_MFP	2
#define DES_GPIO_A(n)	(0x2B0 + 3 * (n))
#define DES_GPIO_B(n)	(0x2B1 + 3 * (n))
"""


def mode_nodes(sif, vc, serdes=True):
    modes = []
    for m, md in enumerate(MODES):
        modes.append(f"""
				mode{m} {{	/* {md['w']}x{md['h']} RAW12 (mono, read as Y12) */
					mclk_khz = "74250";
					num_lanes = "4";
					tegra_sinterface = "{sif}";
					vc_id = "{vc}";
					discontinuous_clk = "no";
					dpcm_enable = "false";
					cil_settletime = "0";
					dynamic_pixel_bit_depth = "12";
					csi_pixel_bit_depth = "12";
					mode_type = "bayer";
					pixel_phase = "rggb";	/* mono sensor: no CFA, ISP not used */
					active_w = "{md['w']}";
					active_h = "{md['h']}";
					readout_orientation = "0";
					line_length = "{4 * md['line_length']}";	/* 4 x HMAX: 1H = line_length / pix_clk_hz */
					inherent_gain = "1";
					pix_clk_hz = "297000000";	/* 4 x 74.25 MHz, >= peak pixel rate */{{SERDES}}
					gain_factor = "10";
					min_gain_val = "0";
					max_gain_val = "480";	/* 48.0 dB */
					step_gain_val = "1";
					default_gain = "0";
					min_hdr_ratio = "1";
					max_hdr_ratio = "1";
					framerate_factor = "1000000";
					min_framerate = "1000000";
					max_framerate = "{md['maxfps']}000000";
					step_framerate = "1";
					default_framerate = "30000000";
					exposure_factor = "1000000";
					min_exp_time = "10";
					max_exp_time = "{md['maxexp']}";
					step_exp_time = "1";
					default_exp_time = "{md['defexp']}";
					embedded_metadata_height = "0";
				}};""".replace("{SERDES}", '\n\t\t\t\t\tserdes_pix_clk_hz = "833333333";' if serdes else ""))
    return "".join(modes)


def sensor(k, side, vc):
    nv_port, vi_port, sif = CSI[k]
    addr = 0x1B if side == "a" else 0x1C
    idx = 2 * k + vc
    modes = [mode_nodes(sif, vc)]
    return f"""
			imx568_{idx}: imx568_{side}@{addr:x} {{
				compatible = "sony,imx568";
				reg = <0x{addr:x}>;		/* proxy address seen by Tegra */
				def-addr = <0x1a>;		/* IMX568 common 2nd address (DS 14.4) */
				devnode = "video{idx}";
				physical_w = "6.708";
				physical_h = "5.612";
				sensor_model = "imx568";
				use_sensor_mode_id = "true";
				post_crop_frame_drop = "0";
				nvidia,gmsl-ser-device = <&ser{k}_{side}>;
				nvidia,gmsl-dser-device = <&dser{k}>;

				imx568,sync-mode = "fast-trigger";	/* or "master" for bring-up */
				imx568,mfp-en = <SER_MFP_EN_1V1 SER_MFP_EN_1V8 SER_MFP_EN_2V9 SER_MFP_EN_3V3>;
				imx568,mfp-xclr = <SER_MFP_XCLR>;
				imx568,mfp-xtrig = <SER_MFP_XTRIG>;
				imx568,mfp-tout0 = <SER_MFP_TOUT0>;
				imx568,gmsl-gpio-id-trig = <0>;
				imx568,gmsl-gpio-id-tout0 = <{1 + vc}>;
				/* imx568,dser-phy-rate-mbps = <2000>;  needed for 2448x2048 above ~25 fps */
				imx568,dser-init-regs = /bits/ 16 <DES_GPIO_A(DES_TRIG_MFP) 0x03
								   DES_GPIO_B(DES_TRIG_MFP) 0x00>;
{''.join(modes)}

				ports {{
					#address-cells = <1>;
					#size-cells = <0>;
					port@0 {{
						reg = <0>;
						imx568_out{idx}: endpoint {{
							vc-id = <{vc}>;
							port-index = <{nv_port}>;
							bus-width = <4>;
							remote-endpoint = <&imx568_csi_in{idx}>;
						}};
					}};
				}};

				gmsl-link {{
					src-csi-port = "b";	/* MAX9295A CSI input */
					dst-csi-port = "a";	/* MAX9296A CSI output port A (x4) */
					serdes-csi-link = "{side}";
					csi-mode = "1x4";
					st-vc = <0>;
					vc-id = <{vc}>;
					num-lanes = <4>;
					streams = "raw12";
				}};
			}};"""


def mux_channel(k):
    return f"""
		i2c@{k} {{	/* stereo pair {k} ({PAIR_NAMES[k]}) */
			reg = <{k}>;
			i2c-mux,deselect-on-exit;
			#address-cells = <1>;
			#size-cells = <0>;

			dser{k}: max9296@48 {{
				compatible = "maxim,max9296";
				reg = <0x48>;
				csi-mode = "2x4";
				max-src = <2>;
				reset-gpios = <&tegra_main_gpio DES{k}_PWDN_GPIO GPIO_ACTIVE_HIGH>;
			}};
			ser{k}_prim: max9295_prim@62 {{
				compatible = "maxim,max9295";
				reg = <0x62>;		/* power-on address (CFG strap) */
				is-prim-ser;
			}};
			ser{k}_a: max9295_a@40 {{
				compatible = "maxim,max9295";
				reg = <0x40>;
				nvidia,gmsl-dser-device = <&dser{k}>;
			}};
			ser{k}_b: max9295_b@60 {{
				compatible = "maxim,max9295";
				reg = <0x60>;
				nvidia,gmsl-dser-device = <&dser{k}>;
			}};
{sensor(k, "a", 0)}
{sensor(k, "b", 1)}
		}};"""


def vi_and_csi():
    vi, cs = [], []
    for k in range(4):
        nv_port, vi_port, _ = CSI[k]
        for vc in (0, 1):
            i = 2 * k + vc
            vi.append(f"""
			port@{i} {{
				reg = <{i}>;
				imx568_vi_in{i}: endpoint {{
					vc-id = <{vc}>;
					port-index = <{vi_port}>;
					bus-width = <4>;
					remote-endpoint = <&imx568_csi_out{i}>;
				}};
			}};""")
            cs.append(f"""
			channel@{i} {{
				reg = <{i}>;
				ports {{
					#address-cells = <1>;
					#size-cells = <0>;
					port@0 {{
						reg = <0>;
						imx568_csi_in{i}: endpoint@{2 * i} {{
							port-index = <{nv_port}>;
							bus-width = <4>;
							remote-endpoint = <&imx568_out{i}>;
						}};
					}};
					port@1 {{
						reg = <1>;
						imx568_csi_out{i}: endpoint@{2 * i + 1} {{
							remote-endpoint = <&imx568_vi_in{i}>;
						}};
					}};
				}};
			}};""")
    return "".join(vi), "".join(cs)


def platform():
    mods = []
    for k in range(4):
        for vc, side in ((0, "a"), (1, "b")):
            i = 2 * k + vc
            addr = 0x1B if side == "a" else 0x1C
            mods.append(f"""
			module{i} {{
				badge = "imx568_{PAIR_NAMES[k]}_{'left' if vc == 0 else 'right'}";
				position = "{['front', 'rear', 'topleft', 'topright', 'bottomleft', 'bottomright', 'centerleft', 'centerright'][i]}";
				orientation = "1";
				drivernode0 {{
					pcl_id = "v4l2_sensor";
					devname = "imx568 {30 + k}-00{addr:02x}";
					proc-device-tree = "/proc/device-tree/i2c@3180000/tca9546@70/i2c@{k}/imx568_{side}@{addr:x}";
				}};
			}};""")
    return "".join(mods)


def main():
    vi, cs = vi_and_csi()
    body = f"""{HDR}
/ {{
	tegra-capture-vi {{
		num-channels = <8>;
		ports {{
			#address-cells = <1>;
			#size-cells = <0>;{vi}
		}};
	}};

	host1x@13e00000 {{
		nvcsi@15a00000 {{
			num-channels = <8>;
			#address-cells = <1>;
			#size-cells = <0>;{cs}
		}};
	}};

	i2c@3180000 {{			/* CAM_I2C on the Xavier camera connector */
		tca9546@70 {{
			compatible = "nxp,pca9546";
			reg = <0x70>;
			#address-cells = <1>;
			#size-cells = <0>;
			skip_mux_detect = "yes";
			vcc_lp = "vcc";
			force_bus_start = <30>;	/* mux channels become i2c-30..33 */
{''.join(mux_channel(k) for k in range(4))}
		}};
	}};

	tegra-camera-platform {{
		compatible = "nvidia, tegra-camera-platform";
		num_csi_lanes = <16>;
		max_lane_speed = <2500000>;
		min_bits_per_pixel = <12>;
		vi_peak_byte_per_pixel = <2>;
		vi_bw_margin_pct = <25>;
		max_pixel_rate = <2400000>;
		isp_peak_byte_per_pixel = <5>;
		isp_bw_margin_pct = <25>;
		modules {{{platform()}
		}};
	}};
}};
"""
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "tegra194-camera-imx568-gmsl-8cam.dtsi")
    with open(out, "w") as fh:
        fh.write(body)
    print(out)


if __name__ == "__main__":
    main()
